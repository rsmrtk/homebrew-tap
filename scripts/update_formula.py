#!/usr/bin/env python3
"""Regenerate Formula/helmsman.rb from the latest GitHub release of rsmrtk/helmsman.

The formula text is produced from the release's own checksums.sha256, so the tap never holds a hand-typed hash.
Prints the version it wrote; exits 0 without touching the file when it is already current.
"""
import json
import re
import sys
import urllib.request

REPO = "rsmrtk/helmsman"
FORMULA = "Formula/helmsman.rb"
ASSETS = {  # (os block, arch block) -> release asset
    ("macos", "arm"): "helmsman_Darwin_arm64.tar.gz",
    ("macos", "intel"): "helmsman_Darwin_amd64.tar.gz",
    ("linux", "arm"): "helmsman_Linux_arm64.tar.gz",
    ("linux", "intel"): "helmsman_Linux_amd64.tar.gz",
}


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "helmsman-tap"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main() -> int:
    rel = json.loads(get(f"https://api.github.com/repos/{REPO}/releases/latest"))
    tag = rel["tag_name"]
    version = tag.lstrip("v")
    base = f"https://github.com/{REPO}/releases/download/{tag}"
    sums = dict(reversed(line.split(None, 1)) for line in get(f"{base}/checksums.sha256").decode().splitlines() if line.strip())
    sums = {k.strip().lstrip("*"): v.strip() for k, v in sums.items()}
    missing = [a for a in ASSETS.values() if a not in sums]
    if missing:
        print(f"release {tag} has no checksums for {missing}", file=sys.stderr)
        return 1

    def block(osname: str) -> str:
        out = [f"  on_{osname} do"]
        for arch in ("arm", "intel"):
            asset = ASSETS[(osname, arch)]
            out += [f"    on_{arch} do",
                    f'      url "https://github.com/{REPO}/releases/download/v#{{version}}/{asset}"',
                    f'      sha256 "{sums[asset]}"', "    end"]
        out.append("  end")
        return "\n".join(out)

    text = f'''# Generated by scripts/update_formula.py from the latest release. Do not edit by hand.
class Helmsman < Formula
  desc "Terminal UI for Kubernetes that shows what is wrong at a glance"
  homepage "https://github.com/{REPO}"
  version "{version}"
  license "Apache-2.0"

{block("macos")}

{block("linux")}

  def install
    bin.install "helmsman"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/helmsman version 2>&1")
  end
end
'''
    try:
        current = open(FORMULA).read()
    except FileNotFoundError:
        current = ""
    if re.sub(r"\s+", " ", current) == re.sub(r"\s+", " ", text):
        print(f"already at {version}")
        return 0
    open(FORMULA, "w").write(text)
    print(f"updated to {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
